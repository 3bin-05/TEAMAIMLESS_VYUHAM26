from datetime import datetime
from typing import Any, Literal, Optional
from pydantic import BaseModel, Field, model_validator


class AIEvidenceInput(BaseModel):
    """Normalized evidence passed into the AI analysis layer."""
    url: str
    domain: str
    ml_status: Optional[str] = "completed"
    ml_prediction: Optional[str] = None
    ml_confidence: Optional[float] = None
    google_status: Optional[str] = "unavailable"
    google_threat_detected: Optional[bool] = None
    google_threat_types: list[str] = Field(default_factory=list)
    virustotal_status: Optional[str] = "unavailable"
    virustotal_malicious: Optional[int] = 0
    virustotal_suspicious: Optional[int] = 0
    virustotal_harmless: Optional[int] = 0
    rdap_status: Optional[str] = "completed"
    domain_age_days: Optional[int] = None
    registrar: Optional[str] = None
    domain_shield_status: Optional[str] = "completed"
    domain_impersonation_detected: Optional[bool] = False
    domain_matched_brand: Optional[str] = None
    content_status: Optional[str] = "completed"
    content_title: Optional[str] = None
    content_meta_description: Optional[str] = None
    has_login_form: Optional[bool] = False
    has_password_field: Optional[bool] = False
    content_suspicious_patterns: list[str] = Field(default_factory=list)
    technical_anomalies: list[dict[str, Any]] = Field(default_factory=list)


class AIReasonItem(BaseModel):
    title: str = Field(..., description="Short descriptive title of the reason")
    explanation: str = Field(..., description="Evidence-backed explanation")
    source: str = Field(..., description="Source of evidence e.g. Domain investigation, VirusTotal, Google threat intelligence")
    severity: Literal["low", "medium", "high", "critical"] = Field(default="medium", description="Severity level")


class AIAnomalyItem(BaseModel):
    title: str = Field(..., description="Anomaly title")
    explanation: str = Field(..., description="Plain-English explanation of technical anomaly")
    source: str = Field(default="Backend anomaly analysis", description="Source of anomaly")


class AIDomainHistory(BaseModel):
    status: str = Field(default="unknown", description="established, limited, new, or unknown")
    explanation: str = Field(default="Domain history evaluated from registration data.", description="Explanation of domain history")


class AIOrganizationVerification(BaseModel):
    status: str = Field(default="unverified", description="verified, unverified, impersonation_suspected, or inconclusive")
    explanation: str = Field(default="Organizational legitimacy evaluated from brand and domain association.", description="Explanation of organizational legitimacy")


class AIStructuredAnalysis(BaseModel):
    """Validated structured intelligence generated by local Ollama LLM as per Phase 15."""
    risk_level: Literal["safe", "suspicious", "malicious", "inconclusive"] = Field(
        default="inconclusive",
        description="Authoritative AI risk level"
    )
    summary: str = Field(
        default="Security analysis completed.",
        description="Concise 1-3 sentence evidence-driven AI summary of the verdict"
    )
    reasons: list[AIReasonItem] = Field(
        default_factory=list,
        description="Structured list of evidence-backed findings explaining the verdict"
    )
    anomalies: list[AIAnomalyItem] = Field(
        default_factory=list,
        description="Technical anomalies detected in domain or URL structure"
    )
    domain_history: AIDomainHistory = Field(
        default_factory=AIDomainHistory,
        description="Evaluation of domain registration age and credibility"
    )
    organization_verification: AIOrganizationVerification = Field(
        default_factory=AIOrganizationVerification,
        description="Evaluation of organizational legitimacy and brand impersonation"
    )
    similar_sites: list[str] = Field(
        default_factory=list,
        description="Known legitimate sites if impersonation or lookalike detected"
    )
    recommendation: Literal["allow", "warn", "block", "inconclusive"] = Field(
        default="inconclusive",
        description="Recommended action: allow, warn, block, or inconclusive"
    )

    # Backward-compatible fields
    verdict_interpretation: Optional[Literal["SUSPICIOUS", "LEGITIMATE", "UNCERTAIN"]] = None
    explanation: Optional[str] = None
    suspicious_indicators: list[str] = Field(default_factory=list)
    benign_indicators: list[str] = Field(default_factory=list)
    confidence_score: float = Field(default=0.9, ge=0.0, le=1.0)
    recommended_action: Optional[Literal["BLOCK", "WARN", "PROCEED_WITH_CAUTION", "ALLOW"]] = None
    next_steps: Optional[str] = "Exercise standard security hygiene."

    @model_validator(mode="before")
    @classmethod
    def from_legacy_data(cls, data: Any) -> Any:
        if not isinstance(data, dict):
            return data
        d = dict(data)
        if "summary" not in d and "explanation" in d:
            d["summary"] = d["explanation"]
        elif "explanation" not in d and "summary" in d:
            d["explanation"] = d["summary"]

        if "risk_level" not in d:
            vi = str(d.get("verdict_interpretation", "")).upper()
            if vi == "LEGITIMATE":
                d["risk_level"] = "safe"
            elif vi == "SUSPICIOUS":
                d["risk_level"] = "suspicious"
            else:
                d["risk_level"] = "inconclusive"

        if "recommendation" not in d:
            ra = str(d.get("recommended_action", "")).upper()
            if ra == "ALLOW":
                d["recommendation"] = "allow"
            elif ra == "BLOCK":
                d["recommendation"] = "block"
            elif ra in ("WARN", "PROCEED_WITH_CAUTION"):
                d["recommendation"] = "warn"
            else:
                d["recommendation"] = "inconclusive"
        return d

    def model_post_init(self, __context: Any) -> None:
        if self.explanation is None:
            self.explanation = self.summary
        if self.verdict_interpretation is None:
            if self.risk_level == "safe":
                self.verdict_interpretation = "LEGITIMATE"
            elif self.risk_level in ("malicious", "suspicious"):
                self.verdict_interpretation = "SUSPICIOUS"
            else:
                self.verdict_interpretation = "UNCERTAIN"
        if self.recommended_action is None:
            if self.recommendation == "allow":
                self.recommended_action = "ALLOW"
            elif self.recommendation == "block":
                self.recommended_action = "BLOCK"
            elif self.recommendation == "warn":
                self.recommended_action = "WARN"
            else:
                self.recommended_action = "PROCEED_WITH_CAUTION"


class AIAnalysisResult(BaseModel):
    """Overall AI result container encapsulating provider metadata, latency, and analysis."""
    status: Literal["completed", "unavailable", "disabled", "failed", "skipped"]
    provider: str = Field(default="none", description="local_ollama, cloud_claude, or none")
    model: str = Field(default="none", description="Model name / tag used for inference")
    is_cloud: bool = Field(default=False, description="True if inference executed via cloud API")
    latency_ms: Optional[float] = Field(default=None, description="Inference latency in milliseconds")
    analysis: Optional[AIStructuredAnalysis] = None
    raw_explanation: Optional[str] = None
    error_reason: Optional[str] = None


class AIStatusResponse(BaseModel):
    """Operational status report for GET /api/v1/ai/status."""
    mode: str = Field(..., description="Configured routing mode: AUTO, LOCAL_ONLY, CLOUD_ONLY, DISABLED")
    ollama_available: bool = Field(..., description="True if local Ollama daemon is reachable and model is verified")
    ollama_reachable: bool = Field(..., description="True if local Ollama endpoint responds to health check")
    ollama_models_found: list[str] = Field(default_factory=list, description="Models currently installed in local Ollama")
    ollama_selected_model: Optional[str] = Field(default=None, description="Active local model tag selected for inference")
    ollama_inference_verified: bool = Field(..., description="True if local health inference test succeeded")
    cloud_ai_configured: bool = Field(..., description="True if Anthropic API key is provided in settings")
    cloud_ai_enabled: bool = Field(..., description="True if AEGIS_CLOUD_AI_ENABLED consent flag is True")
    cloud_model: Optional[str] = Field(default=None, description="Configured Anthropic model name")
    preferred_provider: str = Field(..., description="Provider selected by router under current state")
    last_health_check: Optional[datetime] = None
